async function main() {
  console.log(' Очищаю таблицы...');
  await prisma.planItem.deleteMany();
  await prisma.favorite.deleteMany();
  await prisma.comment.deleteMany();
  await prisma.recipeIngredient.deleteMany();
  await prisma.recipe.deleteMany();
  await prisma.ingredient.deleteMany();
  await prisma.category.deleteMany();
  await prisma.user.deleteMany();

  console.log('👤 Создаю демо-пользователя...');
  const demo = await prisma.user.create({
    data: {
      email: 'demo@cookbook.com',
      name: 'Демо Пользователь',
      passwordHash: await bcrypt.hash('demo123', 10),
    },
  });

  console.log('🗂️ Категории...');
  const categories = new Map<string, string>();
  for (const name of CATEGORIES) {
    const c = await prisma.category.create({ data: { name } });
    categories.set(name, c.id);
  }

  console.log('🥕 Ингредиенты...');
  const ingredients = new Map<string, string>();
  const names = [...new Set(RECIPES.flatMap((r) => r.ingredients.map(([n]) => n)))];
  for (const name of names) {
    const i = await prisma.ingredient.create({ data: { name } });
    ingredients.set(name, i.id);
  }

  console.log('🍽️ Рецепты...');
  for (const r of RECIPES) {
    await prisma.recipe.create({
      data: {
        title: r.title,
        description: r.description,
        cookingTime: r.cookingTime,
        servings: r.servings,
        imageUrl: r.imageUrl,
        rating: r.rating,
        steps: r.steps,
        categoryId: categories.get(r.category)!,
        authorId: demo.id,
        ingredients: {
          create: r.ingredients.map(([name, quantity, unit]) => ({
            quantity,
            unit,
            ingredientId: ingredients.get(name)!,
          })),
        },
      },
    });
  }

  const soup = await prisma.recipe.findFirst({ where: { title: 'Куриный суп с рисом' } });
  if (soup) {
    await prisma.comment.create({
      data: { recipeId: soup.id, userId: demo.id, text: 'Отличный рецепт! Очень понравилось всей семье!' },
    });
  }

  console.log('✅ Seed завершён: 1 пользователь, 12 рецептов, 8 категорий');
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
